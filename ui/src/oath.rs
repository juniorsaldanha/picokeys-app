#[component]
pub fn OathPage() -> Element {
    let mut list = use_resource(api::oath_list);
    let mut now = use_signal(api::now_secs);
    let mut adding = use_signal(|| false);
    let mut query = use_signal(String::new);
    let mut pw_open = use_signal(|| false);

    // 1 s ticker for countdowns; refresh codes when the 30 s window rolls over.
    use_future(move || async move {
        loop {
            api::sleep_ms(1000).await;
            let t = api::now_secs();
            let rolled = (t / 30.0).floor() != (*now.peek() / 30.0).floor();
            now.set(t);
            if rolled {
                list.restart();
            }
        }
    });

    let body = match &*list.read() {
        Some(Ok(accounts)) => {
            let q = query.read().to_lowercase();
            let shown: Vec<OathAccount> = accounts
                .iter()
                .filter(|a| q.is_empty() || a.name.to_lowercase().contains(&q))
                .cloned()
                .collect();
            if accounts.is_empty() && !adding() {
                rsx! {
                    Empty { class: "py-16",
                        EmptyHeader {
                            EmptyMedia { variant: EmptyMediaVariant::Icon, ShieldCheck {} }
                            EmptyTitle { "No authenticator accounts" }
                            EmptyDescription { "Add the setup key or otpauth:// link a website shows when you enable two-factor sign-in." }
                        }
                        EmptyContent {
                            Button { onclick: move |_| adding.set(true), Plus {} "Add account" }
                        }
                    }
                }
            } else {
                rsx! {
                    if accounts.len() > 4 {
                        div { class: "relative mb-4",
                            Search { class: "pointer-events-none absolute left-3 top-1/2 size-4 -translate-y-1/2 text-muted-foreground" }
                            Input {
                                class: "pl-9",
                                r#type: InputType::Search,
                                placeholder: "Search accounts…",
                                value: query(),
                                oninput: move |e: FormEvent| query.set(e.value()),
                            }
                        }
                    }
                    div { class: "grid gap-3 sm:grid-cols-2 xl:grid-cols-3",
                        for a in shown {
                            AccountCard { key: "{a.name}", account: a.clone(), now: now(), on_change: move |_| list.restart() }
                        }
                    }
                }
            }
        }
        Some(Err(e)) if e == "OATH_LOCKED" => rsx! { OathUnlock { on_done: move |_| list.restart() } },
        Some(Err(e)) => rsx! { ErrorBox { title: "Couldn't read authenticator accounts", msg: humanize(e) } },
        None => rsx! {
            div { class: "grid gap-3 sm:grid-cols-2 xl:grid-cols-3",
                for _ in 0..3 { Skeleton { class: "h-36 rounded-xl" } }
            }
        },
    };

    rsx! {
        PageHeader { title: "Authenticator", subtitle: "One-time codes (TOTP/HOTP) generated by your key.",
            Button { variant: ButtonVariant::Outline, size: ButtonSize::Sm, onclick: move |_| list.restart(), RefreshCw {} "Refresh" }
            Button { variant: ButtonVariant::Outline, size: ButtonSize::Sm, onclick: move |_| pw_open.toggle(), Lock {} "Password" }
            Button { size: ButtonSize::Sm, disabled: adding(), onclick: move |_| adding.set(true), Plus {} "Add account" }
        }
        if pw_open() {
            PasswordCard { on_done: move |_| { pw_open.set(false); list.restart(); } }
        }
        if adding() {
            AddAccount {
                on_done: move |saved: bool| {
                    adding.set(false);
                    if saved {
                        list.restart();
                    }
                },
            }
        }
        {body}
    }
}

fn split_code(c: &str) -> String {
    // 123456 → "123 456", 12345678 → "1234 5678"
    let mid = c.len() / 2;
    format!("{} {}", &c[..mid], &c[mid..])
}

#[component]
fn AccountCard(account: OathAccount, now: f64, on_change: EventHandler<()>) -> Element {
    let a = account;
    let mut manual = use_signal(|| None::<String>);
    let mut busy = use_signal(|| false);
    let mut error = use_signal(|| None::<String>);
    let mut copied = use_signal(|| false);
    let mut confirm = use_signal(|| false);
    let mut renaming = use_signal(|| false);
    let mut new_issuer = use_signal({
        let i = a.issuer.clone().unwrap_or_default();
        move || i
    });
    let mut new_account = use_signal({
        let i = a.account.clone();
        move || i
    });

    let code = a.code.clone().or(manual());
    let period = a.period.max(1) as f64;
    let left = period - (now % period);
    let pct = left / period * 100.0;
    let urgent = !a.hotp && left <= 5.0;
    let title = a.issuer.clone().unwrap_or_else(|| a.account.clone());
    let subtitle = if a.issuer.is_some() { a.account.clone() } else { String::new() };
    let initial = title.chars().next().unwrap_or('?').to_uppercase().to_string();

    let name = a.name.clone();
    let generate = move |_| {
        let name = name.clone();
        async move {
            busy.set(true);
            error.set(None);
            match api::oath_calculate(&name).await {
                Ok(c) => manual.set(Some(c)),
                Err(e) => error.set(Some(humanize(&e))),
            }
            busy.set(false);
        }
    };
    let name = a.name.clone();
    let delete = move |_| {
        let name = name.clone();
        async move {
            busy.set(true);
            match api::oath_delete(&name).await {
                Ok(()) => on_change.call(()),
                Err(e) => error.set(Some(humanize(&e))),
            }
            busy.set(false);
        }
    };
    let (old, period) = (a.name.clone(), a.period);
    let rename = move |e: FormEvent| {
        e.prevent_default();
        let old = old.clone();
        async move {
            let (i, acc) = (new_issuer.peek().trim().to_string(), new_account.peek().trim().to_string());
            let mut new = if period != 30 { format!("{period}/") } else { String::new() };
            new += &if i.is_empty() { acc } else { format!("{i}:{acc}") };
            busy.set(true);
            error.set(None);
            match api::oath_rename(&old, &new).await {
                Ok(()) => {
                    renaming.set(false);
                    on_change.call(())
                }
                Err(e) => error.set(Some(humanize(&e))),
            }
            busy.set(false);
        }
    };
    let copy = {
        let code = code.clone();
        move |_| {
            if let Some(c) = &code {
                api::copy_text(c);
                copied.set(true);
                spawn(async move {
                    api::sleep_ms(1200).await;
                    copied.set(false);
                });
            }
        }
    };

    rsx! {
        Card { class: "group gap-3 py-4 transition-shadow hover:shadow-md",
            CardContent { class: "px-4",
                div { class: "flex items-center gap-3",
                    div { class: "flex size-9 shrink-0 items-center justify-center rounded-lg bg-gradient-to-br from-brand-from/15 to-brand-to/15 text-sm font-semibold text-primary",
                        "{initial}"
                    }
                    div { class: "min-w-0 flex-1",
                        div { class: "truncate text-sm font-medium", "{title}" }
                        if !subtitle.is_empty() { div { class: "truncate text-xs text-muted-foreground", "{subtitle}" } }
                    }
                    if a.hotp { Badge { variant: BadgeVariant::Secondary, size: BadgeSize::Sm, "HOTP" } }
                    if a.touch { Badge { variant: BadgeVariant::Info, size: BadgeSize::Sm, "Touch" } }
                    Button {
                        variant: ButtonVariant::Ghost,
                        size: ButtonSize::IconXs,
                        class: "text-muted-foreground opacity-0 transition-opacity group-hover:opacity-100 focus-visible:opacity-100",
                        aria_label: "Rename account",
                        onclick: move |_| renaming.toggle(),
                        Pencil {}
                    }
                    Button {
                        variant: ButtonVariant::Ghost,
                        size: ButtonSize::IconXs,
                        class: "text-muted-foreground opacity-0 transition-opacity group-hover:opacity-100 hover:text-destructive focus-visible:opacity-100",
                        aria_label: "Delete account",
                        onclick: move |_| confirm.set(true),
                        Trash2 {}
                    }
                }

                if renaming() {
                    form { class: "mt-3 flex flex-col gap-2 animate-in fade-in", onsubmit: rename,
                        Input { placeholder: "Issuer (e.g. GitHub)", value: new_issuer(), oninput: move |e: FormEvent| new_issuer.set(e.value()) }
                        Input { placeholder: "Account", value: new_account(), oninput: move |e: FormEvent| new_account.set(e.value()) }
                        div { class: "flex justify-end gap-1.5",
                            Button { variant: ButtonVariant::Ghost, size: ButtonSize::Sm, button_type: "button", onclick: move |_| renaming.set(false), "Cancel" }
                            Button { size: ButtonSize::Sm, button_type: "submit", disabled: busy() || new_account.read().trim().is_empty(),
                                if busy() { Spinner {} } "Rename"
                            }
                        }
                    }
                } else if confirm() {
                    div { class: "mt-4 flex items-center justify-between gap-2 rounded-lg bg-destructive/10 px-3 py-2 animate-in fade-in",
                        span { class: "whitespace-nowrap text-sm", "Delete account?" }
                        div { class: "flex gap-1.5",
                            Button { variant: ButtonVariant::Ghost, size: ButtonSize::Sm, disabled: busy(), onclick: move |_| confirm.set(false), "Cancel" }
                            Button { variant: ButtonVariant::Destructive, size: ButtonSize::Sm, disabled: busy(), onclick: delete,
                                if busy() { Spinner {} } "Delete"
                            }
                        }
                    }
                } else {
                    div { class: "mt-3 flex items-end justify-between gap-3",
                        if let Some(c) = code.clone() {
                            button {
                                class: "selectable -mx-1 rounded-md px-1 text-left font-mono text-3xl font-semibold tracking-wider tabular-nums transition-colors hover:bg-accent/60",
                                class: if urgent { "text-destructive" } else { "" },
                                title: "Click to copy",
                                onclick: copy,
                                "{split_code(&c)}"
                            }
                        } else {
                            Button { variant: ButtonVariant::Outline, size: ButtonSize::Sm, disabled: busy(), onclick: generate,
                                if busy() { Spinner {} } else if a.touch { Fingerprint {} } else { RefreshCw {} }
                                if busy() && a.touch { "Touch the key…" } else if a.hotp { "Generate code" } else { "Touch to reveal" }
                            }
                        }
                        div { class: "flex items-center gap-2 pb-1 text-xs text-muted-foreground",
                            if copied() {
                                span { class: "flex items-center gap-1 text-success animate-in fade-in", Check { class: "size-3.5" } "Copied" }
                            } else if code.is_some() {
                                Copy { class: "size-3.5 opacity-0 transition-opacity group-hover:opacity-100" }
                            }
                            if !a.hotp && a.code.is_some() {
                                // countdown ring
                                svg { class: "size-5 -rotate-90", view_box: "0 0 20 20",
                                    circle { cx: "10", cy: "10", r: "8", fill: "none", stroke: "currentColor", stroke_opacity: "0.15", stroke_width: "2.5" }
                                    circle {
                                        cx: "10", cy: "10", r: "8", fill: "none",
                                        stroke: if urgent { "var(--destructive)" } else { "var(--primary)" },
                                        stroke_width: "2.5",
                                        stroke_linecap: "round",
                                        stroke_dasharray: "50.27",
                                        stroke_dashoffset: "{50.27 * (1.0 - pct / 100.0)}",
                                        style: "transition: stroke-dashoffset 1s linear",
                                    }
                                }
                                span { class: "w-5 tabular-nums", "{left as u32}s" }
                            }
                        }
                    }
                }
                if let Some(e) = error() {
                    p { class: "mt-2 text-xs text-destructive", "{e}" }
                }
            }
        }
    }
}

#[component]
fn AddAccount(on_done: EventHandler<bool>) -> Element {
    let mut form = use_signal(NewOath::default);
    let mut uri = use_signal(String::new);
    let mut uri_error = use_signal(|| None::<String>);
    let mut scanning = use_signal(|| false);
    let mut busy = use_signal(|| false);
    let mut error = use_signal(|| None::<String>);

    let valid = {
        let f = form.read();
        !f.account.trim().is_empty() && !f.secret.trim().is_empty()
    };

    let save = move |e: FormEvent| async move {
        e.prevent_default();
        busy.set(true);
        error.set(None);
        let f = form.peek().clone();
        match api::oath_add(&f).await {
            Ok(()) => on_done.call(true),
            Err(e) => error.set(Some(humanize(&e))),
        }
        busy.set(false);
    };

    let scan = move |_| async move {
        scanning.set(true);
        match api::oath_scan_screen().await.and_then(|u| NewOath::from_uri(&u).map(|n| (u, n))) {
            Ok((u, n)) => {
                uri.set(u);
                form.set(n);
                uri_error.set(None);
            }
            Err(e) => uri_error.set(Some(e)),
        }
        scanning.set(false);
    };

    let select_cls = "h-9 w-full rounded-md border border-input bg-transparent px-2.5 text-sm shadow-xs outline-none focus-visible:ring-2 focus-visible:ring-ring/50 dark:bg-input/30";
    let hotp = form.read().hotp;

    rsx! {
        Card { class: "mb-6 animate-in fade-in slide-in-from-top-2 duration-200",
            CardHeader {
                CardTitle { "Add account" }
                CardDescription { "Paste the otpauth:// link, or type the setup key the website shows." }
            }
            form { onsubmit: save,
                CardContent { class: "flex flex-col gap-4",
                    div { class: "flex flex-col gap-1.5",
                        Label { "otpauth:// link" }
                        div { class: "flex gap-2",
                        Input {
                            class: "font-mono text-xs flex-1",
                            placeholder: "otpauth://totp/Example:alice@example.com?secret=…",
                            value: uri(),
                            oninput: move |e: FormEvent| {
                                let v = e.value();
                                uri.set(v.clone());
                                if v.trim().is_empty() {
                                    uri_error.set(None);
                                    return;
                                }
                                match NewOath::from_uri(&v) {
                                    Ok(n) => { form.set(n); uri_error.set(None) }
                                    Err(e) => uri_error.set(Some(e)),
                                }
                            },
                        }
                        Button { button_type: "button", variant: ButtonVariant::Outline, size: ButtonSize::Sm, class: "h-9 shrink-0", disabled: scanning(), onclick: scan,
                            if scanning() { Spinner {} } else { ScanQrCode {} }
                            "Scan screen"
                        }
                        }
                        p { class: "text-xs text-muted-foreground", "Leave the website's QR code visible on screen, then press Scan screen." }
                        if let Some(e) = uri_error() { p { class: "text-xs text-destructive", "{e}" } }
                    }
                    Separator {}
                    div { class: "grid gap-3 sm:grid-cols-2",
                        div { class: "flex flex-col gap-1.5",
                            Label { "Issuer" }
                            Input { placeholder: "GitHub", value: form.read().issuer.clone(), oninput: move |e: FormEvent| form.with_mut(|f| f.issuer = e.value()) }
                        }
                        div { class: "flex flex-col gap-1.5",
                            Label { "Account" }
                            Input { placeholder: "alice@example.com", value: form.read().account.clone(), oninput: move |e: FormEvent| form.with_mut(|f| f.account = e.value()) }
                        }
                    }
                    div { class: "flex flex-col gap-1.5",
                        Label { "Secret key" }
                        Input { class: "font-mono", placeholder: "JBSW Y3DP EHPK 3PXP", value: form.read().secret.clone(), oninput: move |e: FormEvent| form.with_mut(|f| f.secret = e.value()) }
                    }
                    div { class: "grid grid-cols-2 gap-3 sm:grid-cols-4",
                        div { class: "flex flex-col gap-1.5",
                            Label { "Type" }
                            select { class: select_cls, onchange: move |e: FormEvent| form.with_mut(|f| f.hotp = e.value() == "hotp"),
                                option { value: "totp", selected: !hotp, "Time-based" }
                                option { value: "hotp", selected: hotp, "Counter-based" }
                            }
                        }
                        div { class: "flex flex-col gap-1.5",
                            Label { "Algorithm" }
                            select {
                                class: select_cls,
                                onchange: move |e: FormEvent| form.with_mut(|f| f.algorithm = match e.value().as_str() { "256" => OathAlg::Sha256, "512" => OathAlg::Sha512, _ => OathAlg::Sha1 }),
                                option { value: "1", selected: form.read().algorithm == OathAlg::Sha1, "SHA-1" }
                                option { value: "256", selected: form.read().algorithm == OathAlg::Sha256, "SHA-256" }
                                option { value: "512", selected: form.read().algorithm == OathAlg::Sha512, "SHA-512" }
                            }
                        }
                        div { class: "flex flex-col gap-1.5",
                            Label { "Digits" }
                            select { class: select_cls, onchange: move |e: FormEvent| form.with_mut(|f| f.digits = e.value().parse().unwrap_or(6)),
                                for d in [6u8, 7, 8] { option { value: "{d}", selected: form.read().digits == d, "{d}" } }
                            }
                        }
                        if hotp {
                            div { class: "flex flex-col gap-1.5",
                                Label { "Counter" }
                                Input { r#type: InputType::Number, value: form.read().counter.to_string(), oninput: move |e: FormEvent| form.with_mut(|f| f.counter = e.value().parse().unwrap_or(0)) }
                            }
                        } else {
                            div { class: "flex flex-col gap-1.5",
                                Label { "Period (s)" }
                                Input { r#type: InputType::Number, value: form.read().period.to_string(), oninput: move |e: FormEvent| form.with_mut(|f| f.period = e.value().parse().unwrap_or(30)) }
                            }
                        }
                    }
                    div { class: "flex items-center justify-between gap-4",
                        div {
                            div { class: "text-sm font-medium", "Require touch" }
                            div { class: "text-xs text-muted-foreground", "The key must be touched each time a code is shown." }
                        }
                        Switch { checked: form.read().touch, aria_label: "Require touch", onchange: move |v| form.with_mut(|f| f.touch = v) }
                    }
                    if let Some(e) = error() { p { class: "text-sm text-destructive", "{e}" } }
                }
                CardFooter { class: "mt-4 justify-end gap-2",
                    Button { variant: ButtonVariant::Ghost, disabled: busy(), onclick: move |_| on_done.call(false), "Cancel" }
                    Button { button_type: "submit", disabled: busy() || !valid,
                        if busy() { Spinner {} } else { Plus {} }
                        "Add to key"
                    }
                }
            }
        }
    }
}

#[component]
fn OathUnlock(on_done: EventHandler<()>) -> Element {
    let mut pw = use_signal(String::new);
    let mut busy = use_signal(|| false);
    let mut error = use_signal(|| None::<String>);
    let submit = move |e: FormEvent| async move {
        e.prevent_default();
        busy.set(true);
        error.set(None);
        let p = pw.peek().clone();
        match api::oath_unlock(&p).await {
            Ok(()) => on_done.call(()),
            Err(e) => error.set(Some(humanize(&e))),
        }
        busy.set(false);
    };
    rsx! {
        Card { class: "mx-auto mt-10 w-full max-w-sm animate-in fade-in",
            CardHeader { class: "items-center text-center sm:flex sm:flex-col",
                div { class: "mx-auto mb-2 flex size-12 items-center justify-center rounded-2xl bg-primary/10 text-primary", Lock { class: "size-5" } }
                CardTitle { class: "text-lg", "Authenticator is locked" }
                CardDescription { "Enter the authenticator password. It's separate from the FIDO PIN." }
            }
            CardContent {
                form { class: "flex flex-col gap-3", onsubmit: submit,
                    Input { r#type: InputType::Password, placeholder: "Password", value: pw(), oninput: move |e: FormEvent| pw.set(e.value()) }
                    if let Some(e) = error() { p { class: "text-sm text-destructive", "{e}" } }
                    Button { button_type: "submit", class: "w-full", disabled: busy() || pw.read().is_empty(),
                        if busy() { Spinner {} } else { Lock {} }
                        "Unlock"
                    }
                }
            }
        }
    }
}

/// Set, change or remove the authenticator password.
#[component]
fn PasswordCard(on_done: EventHandler<()>) -> Element {
    let protected = use_resource(api::oath_protected);
    let mut new = use_signal(String::new);
    let mut again = use_signal(String::new);
    let mut busy = use_signal(|| false);
    let mut error = use_signal(|| None::<String>);
    let is_set = matches!(&*protected.read(), Some(Ok(true)));
    let run = move |pw: Option<String>| async move {
        busy.set(true);
        error.set(None);
        match api::oath_set_password(pw.as_deref()).await {
            Ok(()) => on_done.call(()),
            Err(e) if e == "OATH_LOCKED" => error.set(Some("Unlock the authenticator first.".into())),
            Err(e) => error.set(Some(humanize(&e))),
        }
        busy.set(false);
    };
    let mismatch = !again.read().is_empty() && *again.read() != *new.read();
    rsx! {
        Card { class: "mb-6 animate-in fade-in",
            CardHeader {
                CardTitle { if is_set { "Change password" } else { "Set a password" } }
                CardDescription { "Anyone holding the key needs this password to see or use your codes. If you forget it, the authenticator has to be reset." }
            }
            CardContent { class: "flex flex-col gap-3",
                div { class: "grid gap-3 sm:grid-cols-2",
                    Input { r#type: InputType::Password, placeholder: "New password", value: new(), oninput: move |e: FormEvent| new.set(e.value()) }
                    Input { r#type: InputType::Password, placeholder: "Repeat it", value: again(), oninput: move |e: FormEvent| again.set(e.value()) }
                }
                if mismatch { p { class: "text-sm text-muted-foreground", "Passwords don't match." } }
                if let Some(e) = error() { p { class: "text-sm text-destructive", "{e}" } }
                div { class: "flex flex-wrap gap-2",
                    Button { size: ButtonSize::Sm, disabled: busy() || new.read().is_empty() || *again.read() != *new.read(),
                        onclick: move |_| { spawn(run(Some(new.peek().clone()))); },
                        if busy() { Spinner {} } else { Check {} }
                        "Save password"
                    }
                    if is_set {
                        Button { variant: ButtonVariant::Outline, size: ButtonSize::Sm, disabled: busy(), onclick: move |_| { spawn(run(None)); }, "Remove password" }
                        Button { variant: ButtonVariant::Outline, size: ButtonSize::Sm, disabled: busy(),
                            onclick: move |_| async move { let _ = api::oath_lock().await; on_done.call(()) },
                            Lock {} "Lock now"
                        }
                    }
                    Button { variant: ButtonVariant::Ghost, size: ButtonSize::Sm, onclick: move |_| on_done.call(()), "Close" }
                }
            }
        }
    }
}
